const featuredIds = [
  'kullakar-rice',
  'karuppu-kavuni-rice',
  'venthaya-thokku',
  'kasthuri-manjal-soap',
]

export const featuredProducts = products.filter((product) => featuredIds.includes(product.id))

export function productHref(product) {
  return `/product/${product.slug ?? product.id}`
}

export function getProductBySlug(slug) {
  if (!slug) return null
  return products.find((product) => product.id === slug || product.slug === slug) ?? null
}

export function getRelatedProducts(product, limit = 4) {
  if (!product) return []

  const rest = products.filter((item) => item.id !== product.id)
  const sameCategory = rest.filter((item) => item.category === product.category)
  const sameHouse = rest.filter(
    (item) => item.storefront === product.storefront && item.category !== product.category,
  )
  const others = rest.filter((item) => item.storefront !== product.storefront)

  return [...sameCategory, ...sameHouse, ...others].slice(0, limit)
}
